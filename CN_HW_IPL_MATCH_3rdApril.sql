	NO_OF_WINS,
	NO_OF_LOSSES,
	NO_OF_DRAWS,
	COALESCE(CONCAT(NO_OF_DRAWS,'/', NO_OF_WINS), 0) AS NO_OF_DRAWS_OR_WINS
FROM FINAL
ORDER BY NO_OF_WINS DESC, NO_OF_LOSSES ASC, TEAM_NAME ASC;
